LANG_NAMES = {"en": "English", "zh": "中文"}
HTML_LANG = {"zh": "zh-CN"}          # BCP-47 tag for <html lang>, where it differs


def t(lang: str, key: str, **kw) -> str:
    s = STRINGS[lang][key]
    return s.format(**kw) if kw else s


def check_parity():
    """Every language must define exactly the same keys."""
    base = set(STRINGS["en"])
    for lang, d in STRINGS.items():
        missing, extra = base - set(d), set(d) - base
        assert not missing and not extra, f"i18n {lang}: missing {sorted(missing)}, extra {sorted(extra)}"
